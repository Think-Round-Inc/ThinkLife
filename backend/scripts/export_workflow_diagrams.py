"""
Generate the Brain workflow docs from the code (US 1.1 - release traceability).

    python scripts/export_workflow_diagrams.py          # write the files
    python scripts/export_workflow_diagrams.py --check  # exit 1 if they are out of date

Writes, under backend/docs/workflows/:
    brain_workflow.md    Mermaid diagram of the compiled LangGraph workflow (renders on GitHub)
    profiles.md          table of the built-in per-agent workflow profiles

tests/test_workflow_diagrams.py runs the --check comparison, so a change to
the graph that forgets to regenerate these files fails the test suite.
"""

import argparse
import os
import sys
from pathlib import Path
from typing import Dict

BACKEND_DIR = Path(__file__).resolve().parents[1]
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

DOCS_DIR = BACKEND_DIR / "docs" / "workflows"


def render_profiles_table() -> str:
    from brain.cortex.workflow_engine import WORKFLOW_VERSION
    from brain.cortex.workflow_profiles import BUILTIN_PROFILES

    rows = [
        "<!-- Generated by scripts/export_workflow_diagrams.py - do not edit by hand -->",
        f"# Built-in workflow profiles (workflow v{WORKFLOW_VERSION})",
        "",
        "An agent's `ProcessingSpec` overrides `max_iterations`, `run_timeout_seconds` and `safety_checks`; "
        "environment variables can override the LLM judge and fallback providers (see README.md).",
        "",
        "| Profile | Max answer attempts | Run budget (s) | Provider timeout (s) | Provider retries | "
        "Data source retries | LLM judge | Safety checks | Fallback providers |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in sorted(BUILTIN_PROFILES):
        p = BUILTIN_PROFILES[name]
        fallbacks = ", ".join(f"`{f.provider_type}:{f.model}`" for f in p.fallback_providers) or "from env"
        rows.append(
            f"| `{name}` | {p.max_iterations} | {p.run_timeout_seconds:g} | {p.provider_timeout_seconds:g} | "
            f"{p.provider_retry_attempts} | {p.data_source_retry_attempts} | {'on' if p.llm_validation else 'off'} | "
            f"{'on' if p.safety_checks else 'off'} | {fallbacks} |"
        )
    return "\n".join(rows) + "\n"


def render_workflow_page(mermaid: str) -> str:
    from brain.cortex.workflow_engine import WORKFLOW_VERSION

    return (
        "<!-- Generated by scripts/export_workflow_diagrams.py - do not edit by hand -->\n"
        f"# ThinkLife Brain workflow v{WORKFLOW_VERSION}\n\n"
        "Generated from `brain/cortex/workflow_engine.py`. Solid arrows always run; dotted arrows are "
        "conditional routes, labelled with the route name. Dashed boxes are the nodes added in US 1.1. "
        "See [README.md](README.md) for what each node does and the failure table.\n\n"
        f"```mermaid\n{mermaid}```\n"
    )


def render_all() -> Dict[Path, str]:
    from brain.cortex.workflow_engine import WorkflowEngine, describe_graph_mermaid

    engine = WorkflowEngine(checkpointer_kind="none")  # structure only; nothing is run
    return {
        DOCS_DIR / "brain_workflow.md": render_workflow_page(describe_graph_mermaid(engine)),
        DOCS_DIR / "profiles.md": render_profiles_table(),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed files are out of date")
    args = parser.parse_args(argv)

    stale = []
    for path, content in render_all().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(BACKEND_DIR)}")

    if stale:
        for path in stale:
            print(f"out of date: {path.relative_to(BACKEND_DIR)}", file=sys.stderr)
        print("Run: python scripts/export_workflow_diagrams.py", file=sys.stderr)
        return 1
    if args.check:
        print("workflow docs are up to date")
    return 0


if __name__ == "__main__":
    os.environ.setdefault("WORKFLOW_CHECKPOINTER", "none")
    sys.exit(main())
